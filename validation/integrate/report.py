#!/usr/bin/env python3
"""
Generate docs/9_validation_time_integration.md: radot integrate on synthetic ¹⁷⁷Lu time-activity curves.

Usage:
    python validation/integrate/report.py --run      # Monte Carlo (full), writes results/integrate_results.json
    python validation/integrate/report.py            # write the page and its figures from the stored results
    python validation/integrate/report.py --check    # exit 1 if the page is out of date
"""

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import tac_benchmarks as B  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "docs" / "9_validation_time_integration.md"
RESULTS = Path(__file__).resolve().parent / "results" / "integrate_results.json"
N_FULL = 1000
REPO_URL = "https://github.com/dsarrut/radot/tree/main/validation/integrate"


def pct(v, digits=1):
    return "—" if v is None else f"{v:+.{digits}f}"


def cell(r):
    if not r["applicable"]:
        return "n/a"
    if r["bias_pct"] is None:
        return "failed"
    s = f"{r['bias_pct']:+.1f} ± {r['sd_pct']:.1f}"
    if r["failures"]:
        s += f" ({r['failures']} failed)"
    return s


def coverage_cell(r):
    if not r["applicable"] or "coverage_68" not in r:
        return None
    s = f"{100 * r['coverage_68']:.0f} / {100 * r['coverage_95']:.0f}"
    if r["n_se"] < r["n"] - r["failures"]:
        s += f" (SE in {r['n_se']})"
    return s


def render(res: dict) -> str:
    st = res["settings"]
    n = st["n_realisations"]
    noises = [f"{x:g}" for x in st["noises"]]
    schedules = st["schedules"]
    methods = list(B.METHODS)
    L = [
        "<!-- Generated by validation/integrate/report.py. Do not edit by hand. -->",
        "",
        "# Validation of the time integration (synthetic curves)",
        "",
        "`radot integrate` (see [time integration](6e_time_integration.md)) on synthetic ¹⁷⁷Lu "
        "time-activity curves whose integral is known exactly. Each curve is sampled at the times of an "
        "acquisition schedule, with a proportional Gaussian noise; every method sees the same noisy "
        f"realisations ({n} per configuration). Code and data: [validation/integrate]({REPO_URL}).",
        "",
        "## Curves, schedules, methods",
        "",
        "| Curve | Model | Parameters (MBq, 1/h) | Shape | Exact TIA (MBq·h) |",
        "|---|---|---|---|--:|",
    ]
    for k, s in st["shapes"].items():
        L.append(f"| {k} | `{s['model']}` | {', '.join(f'{p:.4g}' for p in s['params'])} | {s['description']} | "
                 f"{res['truth_mbq_h'][k]:.1f} |")
    L += [
        "",
        "| Schedule | Times (h) |",
        "|---|---|",
    ]
    for k, v in schedules.items():
        L.append(f"| {k} | {', '.join(f'{t:g}' for t in v)} |")
    L += [
        "",
        "![The three exact curves and the scan times of each schedule](images/validation_integrate/curves.png)",
        "",
        f"Noise: fractional standard deviation {' and '.join(f'{100 * float(x):g} %' for x in noises)} of "
        "each point.",
        "",
        "| Method | `radot integrate` options |",
        "|---|---|",
    ]
    for m in B.METHODS.values():
        if m.model == "hanscheid2018":
            opts = f"one image, the scan closest to {st['stp_time_h']:g} h, `--model hanscheid2018` (Teff = 2t)"
        else:
            parts = [f"`--model {m.model}`"]
            for key, v in m.options:
                v = ",".join(v) if isinstance(v, tuple) else v
                parts.append(f"`--{key.replace('_', '-')} {v}`")
            if m.known_noise:
                parts.append("`--error-model fsd:<noise>` (the true noise level)")
            opts = " ".join(parts)
        L.append(f"| {m.name} | {opts} |")
    L += [
        "",
        "![One noisy realisation of the lesion at 4 time points and the curves of three methods]"
        "(images/validation_integrate/example.png)",
        "",
        "The example above: `f2` has no uptake and misses the activity before the first scan; the trapezoid "
        "joins the points with straight lines and decays physically after the last one.",
        "",
        "n/a: the method cannot run on this schedule (number of points, Kletting 2013 Table I: fit J ≤ N, "
        "AICc J + 2 ≤ N, with J = K + 1 when the noise level is estimated).",
        "",
        "## Without noise",
        "",
        "Error of the TIA (%) on the exact points: the error of the model itself, for this sampling.",
        "",
    ]
    for shape in st["shapes"]:
        L += [f"**{shape}**", "", "| Method | " + " | ".join(schedules) + " |",
              "|---|" + "--:|" * len(schedules)]
        for m in methods:
            vals = [res["noise_free_pct"][shape][sc][m] for sc in schedules]
            L.append(f"| {m} | " + " | ".join("n/a" if v is None else v if isinstance(v, str) else f"{v:+.2f}"
                                             for v in vals) + " |")
        L.append("")
    L += [
        "## With noise",
        "",
        "Relative error of the TIA (%): mean ± standard deviation over the realisations.",
        "",
        "![Mean error ± SD of the TIA per method, 10 % noise](images/validation_integrate/bias.png)",
        "",
    ]
    cols = [(sc, no) for sc in schedules for no in noises]
    for shape in st["shapes"]:
        L += [f"**{shape}**", "",
              "| Method | " + " | ".join(f"{sc} {100 * float(no):g} %" for sc, no in cols) + " |",
              "|---|" + "--:|" * len(cols)]
        for m in methods:
            L.append(f"| {m} | " + " | ".join(cell(res["results"][shape][sc][no][m]) for sc, no in cols) + " |")
        L.append("")
    L += [
        "## Standard error",
        "",
        "For the fitted models: the fraction of realisations (%) whose exact TIA is within ±1 SE / ±1.96 SE "
        "of the estimate, expected 68 / 95 when the SE is right. `(SE in n)`: realisations with a "
        "standard error (none when the covariance is singular).",
        "",
        "![Coverage of ±1 SE per method](images/validation_integrate/coverage.png)",
        "",
        "Near 68 %: the standard error is right. Far below: the model cannot follow the curve (e.g. `f2` on "
        "the lesion), the error is a bias that no standard error of the fit covers.",
        "",
    ]
    for shape in st["shapes"]:
        rows = []
        for m in methods:
            cells = [coverage_cell(res["results"][shape][sc][no][m]) for sc, no in cols]
            if any(cells):
                rows.append(f"| {m} | " + " | ".join(c or "—" for c in cells) + " |")
        if rows:
            L += [f"**{shape}**", "",
                  "| Method | " + " | ".join(f"{sc} {100 * float(no):g} %" for sc, no in cols) + " |",
                  "|---|" + "--:|" * len(cols), *rows, ""]
    L += [
        "## Reading",
        "",
        "- With the true model and enough points, the fit is unbiased and its standard error is right when "
        "the noise level is known (`fsd`): the coverage is close to 68 / 95 %.",
        "- With the noise level estimated from the points (`proportional`), the standard error is less "
        "reliable: the variance scale comes from very few degrees of freedom (N − K), so the coverage is "
        "often below 68 / 95 %, and above when a model that does not fit the curve inflates the estimated "
        "noise. Give the noise level (`fsd:X`) when it is known.",
        "- `auto` fails when no candidate passes the quality criteria (every parameter CV < 50 %): frequent "
        "for the lesion at 10 % noise. The failures are counted in the tables; radot does not fall back.",
        "- A model without the uptake (`f2`) underestimates a curve with a slow uptake (lesion): the "
        "integral before the first scan is wrong. `f4a` needs the uptake to be visible in the points.",
        "- `trapezoid` with a linear head and a physical-decay tail overestimates the TIA: the physical tail "
        "ignores the biological clearance after the last scan. A fitted tail (`--tail fit`) removes most of "
        "it.",
        "- The single time point method (Hänscheid 2018, Teff = 2t) has a bias that depends on the curve "
        "and the scan time.",
        "",
        "Acceptance (CI, `validation/integrate/test_integrate_validation.py`): exact TIA without noise when the "
        "model contains the curve and the data constrain it; with noise, the true model with the known noise "
        f"at 6 time points has |bias| < {B.TRUE_MODEL_BIAS_PCT:g} % and a coverage of the standard error in "
        f"{B.COVERAGE_68_RANGE[0]:.2f}–{B.COVERAGE_68_RANGE[1]:.2f} (±1 SE) and "
        f"{B.COVERAGE_95_RANGE[0]:.2f}–{B.COVERAGE_95_RANGE[1]:.2f} (±1.96 SE).",
        "",
    ]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run", action="store_true", help=f"run the Monte Carlo ({N_FULL} realisations)")
    ap.add_argument("--check", action="store_true", help="exit 1 if the page is out of date")
    args = ap.parse_args()
    if args.run:
        import warnings

        warnings.simplefilter("ignore")
        res = B.run_all(N_FULL, progress=lambda *a: print(*a, flush=True))
        RESULTS.parent.mkdir(parents=True, exist_ok=True)
        RESULTS.write_text(json.dumps(res, indent=1, allow_nan=False) + "\n")
        print(f"written {RESULTS}")
    res = json.loads(RESULTS.read_text())
    page = render(res)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != page:
            print(f"{OUTPUT} is out of date: run python validation/integrate/report.py")
            sys.exit(1)
        return
    OUTPUT.write_text(page)
    print(f"written {OUTPUT}")
    import figures

    figures.make_all(res)
    print(f"written {figures.IMG_DIR}")


if __name__ == "__main__":
    main()
