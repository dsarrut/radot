#!/usr/bin/env python3
"""
Generate docs/7_validation_opengate.md: radot organ doses compared with OpenGATE Monte Carlo.

The cases and computations are in benchmarks.py; the same comparisons (with the
same acceptance ranges) are asserted in test_opengate.py.

Usage:
    python validation/opengate/report.py          # write docs/7_validation_opengate.md
    python validation/opengate/report.py --check  # exit 1 if the page is out of date
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np

import radot
from benchmarks import CASES, CROSS_TARGETS, cross_dose, evaluate

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "docs" / "7_validation_opengate.md"
V_CONFIG = Path(__file__).resolve().parent / "p142" / "p142_dose_rate_lu177.json"
V_BATCHES = Path(__file__).resolve().parent / "p142" / "p142_lu177_batch_uncertainty.json"
REPO_URL = "https://github.com/dsarrut/radot/tree/main/validation/opengate"
DATA_DOI = "10.5281/zenodo.23696023"


def fmt_sig(x, digits=3):
    """Format with a fixed number of significant digits, keeping trailing zeros."""
    if x == 0:
        return "0"
    decimals = max(0, digits - 1 - int(np.floor(np.log10(abs(x)))))
    return f"{x:.{decimals}f}"


def fmt_range(r):
    if r is None:
        return "—"
    lo, hi = r
    return f"< {hi} %" if lo == 0 else f"{lo}–{hi} %"


def fmt_status(passed):
    if passed is None:
        return "—"
    return "✓" if passed else "✗"


def render(rows):
    self_rows = [r for r in rows if not r["case"].cross]
    cross_rows = [r for r in rows if r["case"].cross]
    bench = self_rows[0]["bench"]
    batches = json.loads(V_BATCHES.read_text(encoding="utf-8"))
    organs = batches["organs"]
    ratios = [o["estimated_uncertainty_fraction"] / o["measured_uncertainty_fraction"] for o in organs.values()]
    lines = [
        "<!-- Generated by validation/opengate/report.py. Do not edit by hand. -->",
        "",
        "# Validation against Monte Carlo",
        "",
        "radot organ doses are compared with full Monte Carlo simulations performed with "
        "[OpenGATE](https://github.com/OpenGATE/opengate) on a patient CT.",
        "",
        "## Setup",
        "",
        f"- **Geometry**: CT of one patient (p142), cropped and resampled to 4 mm. "
        f"Liver volume {float(bench['roi_volume_ml']):.0f} mL, mass {float(bench['roi_mass_g']):.0f} g "
        f"(from CT density).",
        "- **Activity**: uniform in the liver, 1 MBq at t = 0.",
        "- **OpenGATE**: mean dose rate in the organ at t = 0, integrated with a mono-exponential "
        "clearance of effective half-life T<sub>eff</sub>: "
        "D = Ḋ(0) · T<sub>eff</sub> / ln 2.",
        "- **radot**: same activity, same organ mass and the same T<sub>eff</sub>. "
        "Organ-level methods use the OpenDose ICRP-110 adult male S-values, scaled to the patient organ mass.",
        "- **GATE stat. unc.**: statistical uncertainty (one standard deviation) of the organ mean "
        "dose rate, estimated from the voxel uncertainty maps, taking into account that one history "
        "deposits in several voxels (mean β range for electrons, mean organ chord for photons). "
        f"Checked with {batches['n_batches']} independent Lu-177 simulations: "
        f"liver {100 * organs['Liver']['measured_uncertainty_fraction']:.2f} % measured vs "
        f"{100 * organs['Liver']['estimated_uncertainty_fraction']:.2f} % estimated, right kidney "
        f"{100 * organs['Kidney_R']['measured_uncertainty_fraction']:.2f} % vs "
        f"{100 * organs['Kidney_R']['estimated_uncertainty_fraction']:.2f} %; "
        f"for the {len(organs)} organs, the estimate is {min(ratios):.1f} to {max(ratios):.1f} times the measured value.",
        "- **Difference**: (radot − GATE) / GATE.",
        "- **Expected**: acceptance range for |difference| asserted in `validation/opengate/test_opengate.py`.",
        "",
        "## Self-dose (liver ← liver)",
        "",
        "Doses in mGy per MBq present in the liver at t = 0.",
        "",
        "| Radionuclide | T<sub>eff</sub> (h) | Method | radot | GATE | GATE stat. unc. | Difference | Expected | | Note |",
        "|---|--:|---|--:|--:|--:|--:|--:|:-:|---|",
    ]
    for r in self_rows:
        c = r["case"]
        lines.append(
            f"| {c.isotope} | {r['teff_h']:.1f} | {c.label} | {fmt_sig(r['radot'])} | {fmt_sig(r['gate'])} "
            f"| {r['gate_unc']:.1f} % | {r['diff']:+.1f} % | {fmt_range(c.accept)} "
            f"| {fmt_status(r['passed'])} | {c.note} |"
        )

    lines += [
        "",
        "## Cross-dose (organ ← liver)",
        "",
        "Doses in mGy per MBq present in the liver at t = 0. Organs entirely inside the CT, sorted by "
        "their closest distance to the liver. Stomach and heart are segmented whole: OpenDose wall + "
        "contents (mass-weighted S-value). Only the right kidney is checked; the other organs are shown.",
        "",
        "| Radionuclide | Organ ← liver | Mass (g) | Distance (mm) | Method | radot | GATE | GATE stat. unc. | Difference | Expected | |",
        "|---|---|--:|--:|---|--:|--:|--:|--:|--:|:-:|",
    ]
    def cross_key(r):
        c = r["case"]
        return (c.isotope != "Lu177", cross_dose(r["bench"], c.target)["min_distance_to_source_mm"], c.target, c.method != "madsen2018")

    for r in sorted(cross_rows, key=cross_key):
        c = r["case"]
        cross = cross_dose(r["bench"], c.target)
        lines.append(
            f"| {c.isotope} | {c.target} | {cross['target_mass_g']:.0f} | {cross['min_distance_to_source_mm']:.0f} "
            f"| {c.label} | {fmt_sig(r['radot'])} | {fmt_sig(r['gate'])} "
            f"| {r['gate_unc']:.1f} % | {r['diff']:+.1f} % | {fmt_range(c.accept)} "
            f"| {fmt_status(r['passed'])} |"
        )

    lines += [
        "",
        "Cross-doses are about 100 times lower than self-doses and are due to photons. "
        "They depend on the position of the organs and the tissue between them, which differ between "
        "the reference phantom (used for the S-values) and the patient: radot is higher than GATE for "
        "most organs of this patient, by tens of percent and more. The organ-level S-value methods give "
        "the order of magnitude of a cross-dose, not a patient-specific value. "
        "The CT is cropped around the liver (34 cm along the body axis): a simulation on the full-body CT "
        "changes the cross-doses by less than 10 % (left kidney +9 %, heart +3 %, the others within the "
        "statistical uncertainty). "
        "With t = T<sub>eff</sub> / 2, Hänscheid 2018 is identical to Madsen 2018.",
        "",
        "## What this validates",
        "",
        "- The **absorbed dose per decay**: S-values, organ mass scaling, and the energy deposited "
        "locally by the LDM, including decay chains (Ac-225 cascade).",
        "- The handling of several radionuclides with very different emissions "
        "(β⁻ with and without γ, α chain).",
        "",
        "## What this does not validate",
        "",
        "- **Kinetics**: T<sub>eff</sub> is the same for radot and GATE, so the time-integration "
        "models (single-time-point assumptions, curve fitting) are not tested here.",
        "- **Non-uniform activity**: the activity is uniform in the liver; real SPECT distributions "
        "are not yet compared.",
        "- **Other source organs and patients**: one patient, one source organ (liver).",
        "- **Image-based steps**: SPECT quantification, segmentation and registration are outside the scope "
        "of this comparison.",
        "",
        "## How the reference was produced",
        "",
        f"The scripts and configurations are in [`validation/opengate/`]({REPO_URL}); the images and "
        f"OpenGATE outputs are on Zenodo: [doi:{DATA_DOI}](https://doi.org/{DATA_DOI}) (CC-BY-4.0).",
        "",
        "- `p142/prepare/`: preparation of the inputs (resampling to 4 mm, liver mask, cropping around the liver).",
        "- `p142/p142_dose_rate_*.json`: one OpenGATE configuration per radionuclide "
        "(CT, activity image, radionuclide, 1 MBq, simulation mode).",
        "- `p142/create_benchmark_json.py`: reads the OpenGATE dose-rate images and writes the "
        "`p142/p142_*_opengate_benchmark.json` files used on this page.",
        "- `batch_uncertainty.py`: repeats the Lu-177 simulation with different random seeds to "
        "measure the uncertainty of the organ mean (`p142/p142_lu177_batch_uncertainty.json`).",
        "- `benchmarks.py`: the cases and acceptance ranges shown above; "
        "`test_opengate.py`: the same comparisons as tests; `report.py`: this page.",
        "",
        "Each simulation is run with the `opengate_dose_rate` command of OpenGATE, for example:",
        "",
        "```bash",
        "opengate_dose_rate p142_dose_rate_lu177.json",
        "```",
        "",
        "with `p142_dose_rate_lu177.json`:",
        "",
        "```json",
        *(V_CONFIG.read_text(encoding="utf-8").rstrip().splitlines()),
        "```",
        "",
        "To check radot against the stored values, or regenerate this page:",
        "",
        "```bash",
        "pytest validation                             # radot vs the stored OpenGATE values",
        "pytest validation --opengate=images           # same, on the real images (downloads the data)",
        "pytest validation --opengate=simulate         # rerun the OpenGATE simulations, then compare",
        "python validation/opengate/report.py          # regenerate this page",
        "```",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="Do not write; exit with status 1 if the page is out of date.",
    )
    args = parser.parse_args()

    radot.set_log_level("QUIET")
    page = render([evaluate(case) for case in CASES])

    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != page:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date: run python validation/opengate/report.py")
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0

    OUTPUT.write_text(page, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
